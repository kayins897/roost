// Copies the two production cover-material gradients into the preview so the
// comparison shows the real shipped shader fallback, not a re-implementation.
// Source: src/presentation/features/library/cover-material.css
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const src = path.resolve(root, '../../src/presentation/features/library/cover-material.css');

const SELECTORS = [
  '.cover-foil',
  '.cover-foil--holographic',
  '.cover-foil--prismatic',
  '.cover-foil::after',
  '.cover-foil--prismatic::after',
];

const css = await readFile(src, 'utf8');
const blocks = SELECTORS.map((selector) => {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const match = css.match(new RegExp('^' + escaped + ' \\{[^}]*\\}', 'm'));
  if (!match) throw new Error('selector not found in production css: ' + selector);
  return match[0];
});

const header = [
  '/* Generated by tools/extract-prod-css.mjs - do not edit by hand. */',
  '/* Verbatim copy of the shipped gradients in',
  '   src/presentation/features/library/cover-material.css, so the preview compares',
  '   against the real production treatment rather than a lookalike. */',
  '',
].join('\n');

await writeFile(path.join(root, 'prod-material.css'), header + blocks.join('\n') + '\n', 'utf8');
console.log('wrote prod-material.css (' + blocks.length + ' blocks)');